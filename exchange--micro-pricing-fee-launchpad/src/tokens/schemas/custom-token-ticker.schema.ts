import { Prop, Schema, SchemaFactory } from '@nestjs/mongoose';
import { Document } from 'mongoose';

// ─── Types ───────────────────────────────────────────────────────────

export type TickerSource = 'ADMIN' | 'PEG_SYNC' | 'SIMULATION' | 'INTERNAL' | 'SCHEDULED';

// ─── Schema ──────────────────────────────────────────────────────────
//
// CustomTokenTicker = a snapshot of a token's price at a point in time.
// Append-only: every price change creates a new document.
//
// This is the equivalent of CryptoPriceTicker but for launchpad tokens.
// Instead of storing prices from CoinGecko/CMC/CryptoCompare, it stores
// the price set by the broker (manual, peg sync, or simulation).
//
// ─────────────────────────────────────────────────────────────────────

@Schema({ timestamps: true, collection: 'custom_token_tickers' })
export class CustomTokenTicker extends Document {
    @Prop({ required: true, uppercase: true })
    tokenCode: string; // DECOX-USD, DECO-GOV

    // ─── Price ───────────────────────────────────────────────────
    @Prop({ type: Number, required: true })
    priceUsd: number;

    // ─── Source ──────────────────────────────────────────────────
    //   ADMIN      → manually set by admin via API
    //   PEG_SYNC   → automatically updated by peg sync cron
    //   SIMULATION → generated by simulation engine
    //   INTERNAL   → from internal order engine
    //   SCHEDULED  → from scheduled price update
    @Prop({ type: String, enum: ['ADMIN', 'PEG_SYNC', 'SIMULATION', 'INTERNAL', 'SCHEDULED'], default: 'ADMIN' })
    source: TickerSource;

    // ─── Peg Reference (only for PEGGED tokens) ─────────────────
    @Prop({ type: Number })
    pegReferencePrice?: number; // USD price of the peg reference at this moment

    @Prop({ type: Number })
    pegDeviation?: number; // % deviation from expected peg price

    // ─── Audit ───────────────────────────────────────────────────
    @Prop()
    changedBy?: string; // admin user ID or 'system'

    @Prop()
    changeReason?: string; // "Weekly adjustment", "Peg sync", etc.

    // ─── Statistics (calculated from internal data) ──────────────
    @Prop({ type: Number, default: 0 })
    priceChange24h: number; // % change in last 24h (from ticker history)

    @Prop({ type: Number, default: 0 })
    volume24h: number; // Trading volume on the platform (not external)

    @Prop({ type: Number, default: 0 })
    marketCap: number; // price × circulatingSupply

    // ─── Simulation Metadata ─────────────────────────────────────
    @Prop()
    simulationTrend?: string; // Trend at time of generation

    @Prop({ type: Number })
    simulationDrift?: number; // Drift applied in this tick

    // ─── Timestamps ──────────────────────────────────────────────
    @Prop()
    createdAt: Date;

    @Prop()
    updatedAt: Date;
}

export const CustomTokenTickerSchema = SchemaFactory.createForClass(CustomTokenTicker);

// ─── Indexes ─────────────────────────────────────────────────────────
CustomTokenTickerSchema.index({ tokenCode: 1, createdAt: -1 });
CustomTokenTickerSchema.index({ tokenCode: 1, source: 1 });
CustomTokenTickerSchema.index({ createdAt: -1 });

// TTL: auto-delete ticker entries older than 90 days to prevent unbounded growth
CustomTokenTickerSchema.index({ createdAt: 1 }, { expireAfterSeconds: 90 * 24 * 60 * 60 });
