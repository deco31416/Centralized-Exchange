import { Injectable, Logger, NotFoundException } from '@nestjs/common';
import { TokensService } from '../tokens/tokens.service';
import { NetworkDeltasService } from '../network-deltas/network-deltas.service';
import { PriceBandsService } from '../price-bands/price-bands.service';

/**
 * Launchpad Pricing Service
 *
 * Calculates the FINAL BUY/SELL price for custom launchpad tokens.
 * Unlike the crypto pricing micro (which fetches from CoinGecko/CMC/CryptoCompare),
 * this service uses the broker-controlled base price from CustomToken.
 *
 * Pipeline:
 *   1. Get base price (currentPriceUsd from token definition)
 *   2. Apply floor/ceiling validation
 *   3. Add network delta (per-chain cost adjustments)
 *   4. Apply spread (manual or entropy-driven)
 *   5. Return final BUY/SELL price
 *
 * The base price is set by one of 4 mechanisms (pricingModel):
 *   MANUAL     → admin sets via API
 *   PEGGED     → auto-updated by PegSyncService
 *   INTERNAL   → from internal order engine (future)
 *   SIMULATED  → auto-generated by SimulationEngineService
 */
@Injectable()
export class PricingService {
    private readonly logger = new Logger(PricingService.name);

    constructor(
        private readonly tokensService: TokensService,
        private readonly networkDeltasService: NetworkDeltasService,
        private readonly priceBandsService: PriceBandsService,
    ) { }

    // ─── Main Quote Pipeline ─────────────────────────────────────────

    async calculateFinalPrice(tokenCode: string, networkCode: string, operation: 'BUY' | 'SELL') {
        // 1. Get Token Definition (source of truth for base price)
        const token = await this.tokensService.findByCode(tokenCode);
        if (!token.enabled) {
            throw new NotFoundException(`Token ${tokenCode} is disabled/delisted`);
        }

        const basePrice = token.currentPriceUsd;
        if (!basePrice || basePrice <= 0) {
            throw new NotFoundException(`Token ${tokenCode} has no valid price ($${basePrice})`);
        }

        // 2. Floor / Ceiling validation (already enforced by TokensService, but double-check)
        let validatedPrice = basePrice;
        if (token.priceFloorUsd > 0 && validatedPrice < token.priceFloorUsd) {
            validatedPrice = token.priceFloorUsd;
        }
        if (token.priceCeilingUsd > 0 && validatedPrice > token.priceCeilingUsd) {
            validatedPrice = token.priceCeilingUsd;
        }

        // 3. Get Network Delta (same mechanism as crypto pricing)
        //    assetCode in deltas = tokenCode in launchpad
        const delta = await this.networkDeltasService.getDelta(tokenCode, networkCode);
        const deltaUsd = delta?.totalDeltaUsd ?? 0;
        const deltaBreakdown = delta ? {
            manual: delta.manual?.deltaUsd ?? 0,
            emergency: delta.emergency?.deltaUsd ?? 0,
        } : null;

        const priceAfterDelta = validatedPrice + deltaUsd;

        // 4. Get Price Band (with entropy indicator + alerts)
        //    assetCode in bands = tokenCode in launchpad
        const band = await this.priceBandsService.getBand(tokenCode, networkCode);

        const buySpread = band?.effectiveBuySpread ?? band?.buySpreadPercentage ?? -5;
        const sellSpread = band?.effectiveSellSpread ?? band?.sellSpreadPercentage ?? 5;

        // 5. Calculate Final Price
        //    User BUY  = exchange sells → apply sell spread (positive markup)
        //    User SELL = exchange buys  → apply buy spread (negative markdown)
        let finalPrice: number;
        if (operation === 'BUY') {
            finalPrice = priceAfterDelta * (1 + (sellSpread / 100));
        } else {
            finalPrice = priceAfterDelta * (1 + (buySpread / 100));
        }

        // 6. Get latest ticker for 24h stats
        const ticker = await this.tokensService.getLatestTicker(tokenCode);

        return {
            tokenCode,
            tokenName: token.name,
            category: token.category,
            pricingModel: token.pricingModel,
            networkCode,
            operation,
            // Price pipeline
            basePrice: validatedPrice,
            networkDelta: deltaUsd,
            deltaBreakdown,
            priceAfterDelta,
            appliedSpread: operation === 'BUY' ? sellSpread : buySpread,
            finalPrice: Math.round(finalPrice * 1_000_000) / 1_000_000, // 6 decimal precision
            // Token constraints
            priceFloor: token.priceFloorUsd || null,
            priceCeiling: token.priceCeilingUsd || null,
            // Band & Entropy info
            bandMode: band?.mode ?? 'MANUAL',
            entropy: band?.entropy ? {
                score: band.entropy.score,
                level: band.entropy.level,
                recommendedBuySpread: band.entropy.recommendedBuySpread,
                recommendedSellSpread: band.entropy.recommendedSellSpread,
            } : null,
            alertLevel: band?.alertLevel ?? 'SAFE',
            alertMessage: band?.alertMessage,
            // 24h stats
            priceChange24h: ticker?.priceChange24h ?? 0,
            volume24h: ticker?.volume24h ?? 0,
            marketCap: ticker?.marketCap ?? 0,
            // Peg info (if applicable)
            pegInfo: token.pricingModel === 'PEGGED' ? {
                pegType: token.pegConfig?.pegType,
                pegRatio: token.pegConfig?.pegRatio,
                pegCustomAsset: token.pegConfig?.pegCustomAsset,
                lastPegDeviation: ticker?.pegDeviation,
                lastPegReference: ticker?.pegReferencePrice,
            } : undefined,
            // Metadata
            lastPriceUpdate: token.lastPriceUpdateAt,
            lastPriceSource: ticker?.source,
            timestamp: new Date(),
        };
    }

    // ─── Simple Reads ────────────────────────────────────────────────

    async getLatestPrice(tokenCode: string) {
        const token = await this.tokensService.findByCode(tokenCode);
        const ticker = await this.tokensService.getLatestTicker(tokenCode);
        return {
            tokenCode: token.tokenCode,
            name: token.name,
            pricingModel: token.pricingModel,
            currentPriceUsd: token.currentPriceUsd,
            priceChange24h: ticker?.priceChange24h ?? 0,
            volume24h: ticker?.volume24h ?? 0,
            marketCap: ticker?.marketCap ?? 0,
            lastSource: ticker?.source,
            lastUpdate: token.lastPriceUpdateAt,
        };
    }

    async getAllLatestPrices() {
        const [tokens, tickers] = await Promise.all([
            this.tokensService.findEnabled(),
            this.tokensService.getAllLatestTickers(),
        ]);

        // Build a Map for O(1) ticker lookup instead of N queries
        const tickerMap = new Map<string, any>();
        for (const t of tickers) {
            tickerMap.set(t.tokenCode, t);
        }

        return tokens.map(token => {
            const ticker = tickerMap.get(token.tokenCode);
            return {
                tokenCode: token.tokenCode,
                name: token.name,
                category: token.category,
                pricingModel: token.pricingModel,
                currentPriceUsd: token.currentPriceUsd,
                priceChange24h: ticker?.priceChange24h ?? 0,
                volume24h: ticker?.volume24h ?? 0,
                marketCap: ticker?.marketCap ?? 0,
                lastSource: ticker?.source,
                lastUpdate: token.lastPriceUpdateAt,
                enabled: token.enabled,
            };
        });
    }

    /**
     * Bulk quote: calculate final price for ALL enabled tokens on a given network.
     */
    async getAllQuotes(networkCode: string, operation: 'BUY' | 'SELL') {
        const tokens = await this.tokensService.findEnabled();
        const quotes = [];

        for (const token of tokens) {
            try {
                const quote = await this.calculateFinalPrice(token.tokenCode, networkCode, operation);
                quotes.push(quote);
            } catch (error) {
                this.logger.warn(`[BulkQuote] Skipping ${token.tokenCode}: ${error.message}`);
            }
        }

        return quotes;
    }
}
